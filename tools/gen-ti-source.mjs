#!/usr/bin/env node
// Extracts the TI library functions the game runs unchanged (BSD-3-Clause,
// see THIRD_PARTY.md) into src/sim/lib/ti_source.ts.
// Usage: node tools/gen-ti-source.mjs <path to .../device_support/f2837xd>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];
if (!root) {
  console.error("usage: gen-ti-source.mjs <device_support/f2837xd dir>");
  process.exit(1);
}
const WANT = {
  "common/source/F2837xD_Gpio.c": ["InitGpio", "GPIO_SetupPinMux", "GPIO_SetupPinOptions", "GPIO_ReadPin", "GPIO_WritePin"],
  "common/source/F2837xD_CpuTimers.c": ["InitCpuTimers", "ConfigCpuTimer"],
};
const DEFINES = {
  "common/include/F2837xD_Gpio_defines.h": /^#define\s+GP(IO|Y)\w*\s+\S/,
  "common/include/F2837xD_Pie_defines.h": /^#define\s+(PIEACK_GROUP\d+|M_\w+)\s+\S/,
  "headers/include/F2837xD_device.h": /^#define\s+(M_\w+|BIT\d+)\s+\S/,
};

let out = "";
for (const [file, re] of Object.entries(DEFINES)) {
  out += `// ---- ${file}\n`;
  for (const line of readFileSync(join(root, file), "latin1").split(/\r?\n/)) {
    if (re.test(line.trim())) out += line.trim().replace(/\s*\/\/.*$/, "") + "\n";
  }
}
for (const [file, names] of Object.entries(WANT)) {
  const text = readFileSync(join(root, file), "latin1");
  out += `// ---- ${file}\n`;
  for (const name of names) {
    const m = new RegExp(`^[ \\t]*[\\w ]+\\b${name}\\s*\\([^;{]*\\)\\s*\\{`, "m").exec(text);
    if (!m) throw new Error(`${name} not found in ${file}`);
    let depth = 0;
    let i = m.index;
    for (; i < text.length; i++) {
      if (text[i] === "{") depth++;
      if (text[i] === "}" && --depth === 0) break;
    }
    out += text.slice(m.index, i + 1).replace(/\r/g, "") + "\n";
  }
}
const dest = join(import.meta.dirname, "..", "src", "sim", "lib", "ti_source.ts");
writeFileSync(
  dest,
  "// Generated by tools/gen-ti-source.mjs from C2000Ware (Texas Instruments, BSD-3-Clause).\n" +
    "export const TI_SOURCE = " + JSON.stringify(out) + ";\n",
);
console.log(`${out.split("\n").length} lines -> ${dest}`);
