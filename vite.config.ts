import { createHash } from "node:crypto";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import { figureMeta } from "./tools/figure-meta.ts";

// Writes sw.js: a service worker that stores every built file on the first
// visit, so the web version works offline and can be installed from the
// browser. The cache name changes whenever any file changes.
function offline(): Plugin {
  return {
    name: "bringup-offline",
    apply: "build",
    generateBundle(_opts, bundle) {
      const files = ["./", ...Object.keys(bundle).filter((f) => !f.endsWith(".map")), "icon.svg", "icon-256.png", "icon-512.png", "manifest.webmanifest"];
      const hash = createHash("sha256");
      for (const [name, chunk] of Object.entries(bundle)) hash.update(name).update(chunk.type === "chunk" ? chunk.code : chunk.source);
      const version = hash.digest("hex").slice(0, 12);
      const source = `// Generated by vite.config.ts. Do not edit.
const CACHE = "bringup-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("bringup-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin) return;
  // Installers and the install scripts are always fetched fresh.
  if (/\\/(install\\.(sh|ps1)|downloads\\/)/.test(url.pathname)) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit ?? fetch(e.request)));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

// Asks for the body font at once. Without this the browser learns that it needs the font only when
// the first screen is laid out, after the script has run: the first text is then drawn in a fallback
// font and changes a moment later. The file name carries a hash, so it is looked up in the bundle.
function preloadBodyFont(): Plugin {
  return {
    name: "bringup-preload-font",
    apply: "build",
    transformIndexHtml: {
      order: "post",
      handler(_html, ctx) {
        const file = Object.keys(ctx.bundle ?? {}).find((f) => /atkinson-hyperlegible-next-latin-wght-normal-[\w-]+\.woff2$/.test(f));
        // A font is always fetched without credentials: the preload must say the same, or the file is fetched twice.
        return file ? [{ tag: "link", attrs: { rel: "preload", as: "font", type: "font/woff2", href: `./${file}`, crossorigin: "" }, injectTo: "head" }] : [];
      },
    },
  };
}

// Relative base so the build works from the Tauri asset protocol and from
// a sub-folder on GitHub Pages alike.
export default defineConfig({
  base: "./",
  plugins: [react(), figureMeta(), preloadBodyFont(), offline()],
  clearScreen: false,
  server: { port: 5183, strictPort: true },
  // license: the licences of every bundled package, written next to the game (licenses.md).
  build: { target: "es2022", chunkSizeWarningLimit: 2600, license: { fileName: "licenses.md" } },
});
