import { createHash } from "node:crypto";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";

// Writes sw.js: a service worker that stores every built file on the first
// visit, so the web version works offline and can be installed from the
// browser. The cache name changes whenever any file changes.
function offline(): Plugin {
  return {
    name: "bringup-offline",
    apply: "build",
    generateBundle(_opts, bundle) {
      const files = ["./", ...Object.keys(bundle).filter((f) => !f.endsWith(".map")), "icon.svg", "icon-256.png", "icon-512.png", "manifest.webmanifest"];
      const hash = createHash("sha256");
      for (const [name, chunk] of Object.entries(bundle)) hash.update(name).update(chunk.type === "chunk" ? chunk.code : chunk.source);
      const version = hash.digest("hex").slice(0, 12);
      const source = `// Generated by vite.config.ts. Do not edit.
const CACHE = "bringup-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("bringup-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin) return;
  // Installers and the install scripts are always fetched fresh.
  if (/\\/(install\\.(sh|ps1)|downloads\\/)/.test(url.pathname)) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit ?? fetch(e.request)));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

// Relative base so the build works from the Tauri asset protocol and from
// a sub-folder on GitHub Pages alike.
export default defineConfig({
  base: "./",
  plugins: [react(), offline()],
  clearScreen: false,
  server: { port: 5183, strictPort: true },
  build: { target: "es2022", chunkSizeWarningLimit: 1500 },
});
